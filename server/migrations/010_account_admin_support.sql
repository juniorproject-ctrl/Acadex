ALTER TABLE users MODIFY password_hash VARCHAR(255) NULL, ADD deleted_at DATETIME NULL, ADD is_suspended BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE listings ADD is_hidden BOOLEAN NOT NULL DEFAULT FALSE;
CREATE TABLE IF NOT EXISTS app_settings (
 setting_key VARCHAR(100) PRIMARY KEY,
 setting_value VARCHAR(255) NOT NULL
);
CREATE TABLE IF NOT EXISTS admin_audit (
 id CHAR(36) PRIMARY KEY,
 actor_id CHAR(36) NOT NULL,
 action VARCHAR(100) NOT NULL,
 target_id VARCHAR(100) NOT NULL,
 reason VARCHAR(2000) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (actor_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS report_replies (
 id CHAR(36) PRIMARY KEY,
 report_id CHAR(36) NOT NULL,
 author_id CHAR(36) NOT NULL,
 body VARCHAR(2000) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (report_id) REFERENCES reports(id) ON DELETE CASCADE,
 FOREIGN KEY (author_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS support_messages (
 id CHAR(36) PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 email VARCHAR(255) NOT NULL,
 subject VARCHAR(160) NOT NULL,
 message TEXT NOT NULL,
 status ENUM('open','resolved') NOT NULL DEFAULT 'open',
 reply VARCHAR(2000) NOT NULL DEFAULT '',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
